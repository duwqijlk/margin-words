#!/usr/bin/env python3
"""
Self-host the Chinese serif (Noto Serif SC, weight 600) for the book voice: page and dialog titles,
tutorial headings, the word list's big numbers... in Chinese. Google Fonts is slow or blocked for
many readers in China, and the full font is many megabytes, so only the characters the Chinese
interface uses (src/lib/i18n-zh.ts) are kept.

The source is the @fontsource/noto-serif-sc package, which already cuts the font into ~100 chunks
by unicode-range. For every chunk that holds a character the interface uses, this keeps only those
characters, writes public/fonts/zh-serif/<n>.woff2, and writes src/fonts-zh-serif.css with one
@font-face per chunk and its unicode-range, so a page downloads only the chunks it shows.

A character added to i18n-zh.ts later and not in these files falls back to the system serif
(Songti SC, STSong). Run this again after adding many new Chinese strings:

  npm pack @fontsource/noto-serif-sc   # then untar it somewhere
  python3 scripts/subset-zh-serif.py <path to the untarred package directory>

Needs fonttools and brotli (pip install fonttools brotli).
"""
import os
import re
import sys

from fontTools import subset

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FAMILY = "inputread Serif SC"
WEIGHT = 600


def ranges(text):
    out = []
    for part in text.split(","):
        part = part.strip()
        if not part.upper().startswith("U+"):
            continue
        start, _, end = part[2:].partition("-")
        out.append((int(start, 16), int(end, 16) if end else int(start, 16)))
    return out


def main():
    if len(sys.argv) != 2:
        sys.exit("usage: subset-zh-serif.py <@fontsource/noto-serif-sc package directory>")
    pkg = sys.argv[1]
    css = open(os.path.join(pkg, f"{WEIGHT}.css"), encoding="utf-8").read()
    zh = open(os.path.join(ROOT, "src/lib/i18n-zh.ts"), encoding="utf-8").read()
    wanted = {ord(c) for c in zh if ord(c) >= 0x2E80}

    out_dir = os.path.join(ROOT, "public/fonts/zh-serif")
    # Clear the old subsets, but keep the licence that travels with them.
    os.makedirs(out_dir, exist_ok=True)
    for name in os.listdir(out_dir):
        if name.endswith(".woff2"):
            os.remove(os.path.join(out_dir, name))
    faces = []
    for block in re.findall(r"@font-face\s*\{(.*?)\}", css, re.S):
        src = re.search(r"url\(\./files/([^)]+-%d-normal\.woff2)\)" % WEIGHT, block)
        span = re.search(r"unicode-range:\s*([^;]+);", block)
        if not src or not span:
            continue
        spans = ranges(span.group(1))
        chars = sorted(c for c in wanted if any(a <= c <= b for a, b in spans))
        if not chars:
            continue
        name = f"{len(faces):02d}.woff2"
        options = subset.Options()
        options.flavor = "woff2"
        options.layout_features = ["*"]
        options.name_IDs = ["*"]
        font = subset.load_font(os.path.join(pkg, "files", src.group(1)), options)
        subsetter = subset.Subsetter(options)
        subsetter.populate(unicodes=chars)
        subsetter.subset(font)
        subset.save_font(font, os.path.join(out_dir, name), options)
        faces.append((name, ", ".join(f"U+{c:X}" for c in chars)))

    lines = [
        "/* Generated by scripts/subset-zh-serif.py from @fontsource/noto-serif-sc (SIL OFL 1.1). Do not edit. */",
    ]
    for name, chars in faces:
        lines += [
            "@font-face {",
            f'  font-family: "{FAMILY}";',
            "  font-style: normal;",
            f"  font-weight: {WEIGHT};",
            "  font-display: swap;",
            f'  src: url("/fonts/zh-serif/{name}") format("woff2");',
            f"  unicode-range: {chars};",
            "}",
        ]
    with open(os.path.join(ROOT, "src/fonts-zh-serif.css"), "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines) + "\n")
    size = sum(os.path.getsize(os.path.join(out_dir, n)) for n, _ in faces)
    print(f"{len(wanted)} characters, {len(faces)} files, {size // 1024} KB")


if __name__ == "__main__":
    main()
